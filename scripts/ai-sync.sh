#!/usr/bin/env bash
# Build the generated AI instruction files from their sources.
#   scripts/ai-sync.sh            write what changed
#   scripts/ai-sync.sh --check    change nothing; exit 1 when a file is stale
#   scripts/ai-sync.sh --dry-run  show what would change
# Sources: config/ai/AGENTS.md (shared), ~/.config/ai/AGENTS.md (yours),
# ~/.config/ai/scopes/{personal,work}.md (optional, one scope each).
# Output, in the dotfiles state directory (ai/):
#   scope-personal.md, scope-work.md  a heading that limits the scope, and an
#                                     import of the scope file (Claude Code,
#                                     Gemini CLI)
#   AGENTS.md                         everything in one file (Codex, which
#                                     has no imports)
# See docs/ai.md.
set -euo pipefail
# shellcheck source=scripts/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
# shellcheck source=config/shell/local-conf.sh
. "$DOTFILES_DIR/config/shell/local-conf.sh"

CHECK=0
case "${1:-}" in
  --check) CHECK=1 ;;
  -n | --dry-run) DRY_RUN=1 ;;
  "") ;;
  *) die "usage: $0 [--check | --dry-run]" ;;
esac

init_state_paths "$(detect_platform)"
AI_HOME="${XDG_CONFIG_HOME:-$HOME/.config}/ai"
OUT="$STATE_DIR/ai"
PROJECTS="$HOME/projects"
# shellcheck disable=SC2154 # set by _dotfiles_conf_get
if _dotfiles_conf_get DOTFILES_PROJECTS; then PROJECTS=$_dotfiles_conf; fi
case $PROJECTS in "~"/*) PROJECTS="$HOME/${PROJECTS#\~/}" ;; esac
PROJECTS=${PROJECTS%/}
MARK="<!-- Generated by dotfiles scripts/ai-sync.sh. Do not edit: edit the sources and run it again. -->"

scope_heading() { # scope
  printf '## %s scope\n\n' "$(printf '%s' "$1" | awk '{ print toupper(substr($0, 1, 1)) substr($0, 2) }')"
  printf 'Apply this section only when the working directory is inside\n%s/%s/\n' "$PROJECTS" "$1"
  printf '(including worktrees under %s/%s/*/.worktrees/). Ignore it elsewhere.\n\n' "$PROJECTS" "$1"
}

gen_scope() { # scope
  local src="$AI_HOME/scopes/$1.md"
  printf '%s\n' "$MARK"
  if [ -s "$src" ]; then
    scope_heading "$1"
    printf '@%s\n' "$src"
  else
    printf '<!-- No %s instructions: %s does not exist. -->\n' "$1" "$src"
  fi
}

gen_bundle() {
  local s
  printf '%s\n<!-- Sources: %s, %s, %s/scopes/. -->\n\n' "$MARK" "$DOTFILES_DIR/config/ai/AGENTS.md" "$AI_HOME/AGENTS.md" "$AI_HOME"
  cat "$DOTFILES_DIR/config/ai/AGENTS.md"
  if [ -s "$AI_HOME/AGENTS.md" ]; then
    printf '\n'
    cat "$AI_HOME/AGENTS.md"
  fi
  for s in personal work; do
    [ -s "$AI_HOME/scopes/$s.md" ] || continue
    printf '\n'
    scope_heading "$s"
    cat "$AI_HOME/scopes/$s.md"
  done
}

STALE=0
sync_file() { # name, generator
  local target="$OUT/$1" tmp verb=write
  tmp=$(mktemp)
  "$2" "${3:-}" >"$tmp"
  if [ -f "$target" ] && cmp -s "$tmp" "$target"; then
    [ "$CHECK" = 1 ] || ok "$target"
  elif [ "$CHECK" = 1 ]; then
    STALE=1
    echo "stale: $target"
  elif [ -e "$target" ] && ! grep -qF 'Generated by dotfiles' "$target"; then
    rm -f "$tmp"
    die "$target exists and was not generated by dotfiles; not overwritten"
  else
    [ -e "$target" ] && verb=update
    if [ "$DRY_RUN" != 1 ]; then
      mkdir -p "$OUT"
      cp "$tmp" "$target"
    fi
    change "$verb $target"
  fi
  rm -f "$tmp"
}

sync_file scope-personal.md gen_scope personal
sync_file scope-work.md gen_scope work
sync_file AGENTS.md gen_bundle

if [ "$CHECK" = 1 ]; then
  [ "$STALE" = 0 ] || { echo "run scripts/ai-sync.sh to update"; exit 1; }
  exit 0
fi
size=$(gen_bundle | wc -c | tr -d ' ')
[ "$size" -le 32768 ] || warn "$OUT/AGENTS.md is $size bytes; Codex reads 32 KiB by default (project_doc_max_bytes)"
